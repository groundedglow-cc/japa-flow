function sentence(jp, kana, cn) {
  return { jp, kana, cn };
}

function group(id, title, sentences, note = '') {
  return { id, title, ...(note ? { note } : {}), examples: [{ sentences }] };
}

function fromLesson(lessonNo, ids, extra = []) {
  const source = JSON.parse(fs.readFileSync(path.join(root, `data/lessons/lesson${lessonNo}.json`), 'utf8'));
  const byId = new Map(source.sentences.map(item => [item.id, item]));
  const grammar = new Map(source.grammar.map(item => [item.id, item]));
  return ids.map(id => {
    const item = grammar.get(id);
    const values = [...(item?.examples || []).map(key => byId.get(key)).filter(Boolean).map(x => sentence(x.text, x.kana, x.translation)), ...(item?.extraExamples || []).map(x => sentence(x.jp, x.kana, x.cn))];
    const unique = [...new Map(values.map(x => [x.jp, x])).values()];
    return group(id, item?.pattern || id, unique);
  });
}

function page(groups) { return { groups }; }
function write(lessonNo, pages) {
  const data = { schemaVersion: 1, lessonId: `lesson${lessonNo}`, reviewStatus: 'approved', rubyNotation: 'plain-japanese-with-kana-field', pages };
  fs.writeFileSync(path.join(root, `data/ocr/lesson${lessonNo}-grammar-examples.json`), JSON.stringify(data, null, 2) + '\n');
}

