function buildVocabulary(lessonNo, lesson) {
  return {
    lessonId: `lesson${lessonNo}`,
    sourceImages: [{ path: imagePath(lessonNo, lesson.pages.vocab), pageNo: lesson.pages.vocab }],
    vocabulary: lesson.vocabulary.map(([kana, writing, meaningZh, partOfSpeech], index) => ({
      id: `l${lessonNo}-v${String(index + 1).padStart(3, "0")}`,
      kana,
      writing,
      meaningZh,
      partOfSpeech,
      rawText: `${kana}${writing && writing !== kana ? `（${writing}）` : ""}${partOfSpeech ? `[${partOfSpeech}] ` : ""}${meaningZh.join("，")}`,
      confidence: "high"
    })),
    warnings: []
  };
}

function buildText(lessonNo, lesson) {
  return {
    lessonId: `lesson${lessonNo}`,
    sourceImages: [
      { section: "basic", path: imagePath(lessonNo, lesson.pages.basic), pageNo: lesson.pages.basic },
      { section: "application", path: imagePath(lessonNo, lesson.pages.app), pageNo: lesson.pages.app }
    ],
    basicText: {
      title: "基本课文",
      basicSentences: lesson.basicSentences.map(([text, translationZh], index) => ({
        id: `l${lessonNo}-basic-s${String(index + 1).padStart(3, "0")}`,
        order: index + 1,
        text,
        translationZh,
        confidence: "high",
        rawText: `${index + 1}. ${text}`
      })),
      dialogues: lesson.basicDialogues.map(([label, lines], dialogueIndex) => ({
        id: `l${lessonNo}-basic-dialogue-${String(dialogueIndex + 1).padStart(3, "0")}`,
        label,
        lines: lines.map(([speaker, text, translationZh], lineIndex) => ({
          id: `l${lessonNo}-basic-dialogue-${String(dialogueIndex + 1).padStart(3, "0")}-line-${String(lineIndex + 1).padStart(3, "0")}`,
          speaker,
          text,
          translationZh,
          confidence: "high",
          rawText: `${speaker}：${text}`
        }))
      }))
    },
    applicationText: {
      title: lesson.appTitle,
      blocks: lesson.appBlocks.map((block, blockIndex) => {
        const id = `l${lessonNo}-app-block-${String(blockIndex + 1).padStart(3, "0")}`;
        if (block.type !== "dialogue") {
          return {
            id,
            type: block.type,
            text: block.text,
            translationZh: block.translationZh,
            confidence: "high",
            rawText: block.text
          };
        }
        return {
          id,
          type: "dialogue",
          lines: block.lines.map(([speaker, text, translationZh], lineIndex) => ({
            id: `${id}-line-${String(lineIndex + 1).padStart(3, "0")}`,
            speaker,
            text,
            translationZh,
            confidence: "high",
            rawText: `${speaker}：${text}`
          }))
        };
      })
    },
    warnings: [
      "segments/ruby 未批量生成；保留 text 与 translationZh，后续可单独补充 ruby 切片。"
    ]
  };
}

function scene(translationZh) {
  return { type: "scene", text: translationZh, translationZh };
}

function dialogue(lines) {
  return { type: "dialogue", lines };
}

function imagePath(lessonNo, pageNo) {
  return `course-assets/by-lesson/lesson${lessonNo}/page${pageNo}.webp`;
}

function writeJson(fileName, data) {
  const path = join(outDir, fileName);
  writeFileSync(path, `${JSON.stringify(data, null, 2)}\n`);
  console.log(path);
}
